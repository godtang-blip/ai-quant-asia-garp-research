"""Extract context-bound figures from text-bearing official PDF and HTML statements."""
from collections import Counter
from datetime import date, datetime
from io import BytesIO
import re
import unicodedata

from .filing_tables import CURRENCIES, _dates
from .gemini_filing import MAX_PAGES, decimal_text, document_identity


class StatementError(ValueError):
    """A fixed diagnostic for unsupported source or ambiguous context."""


HEADINGS = {
    'IS': re.compile(r'^(?:consolidated (?:income statements?|statements? of (?:profit or loss|income|operations|comprehensive income)).*|'
                     r'合[併并](?:利[润潤]表|綜合損益表|综合损益表))$', re.I),
    'BS': re.compile(r'^(?:consolidated (?:balance sheets?|statements? of financial position).*|合[併并][資资][產产][負负][債债]表)$', re.I),
    'CF': re.compile(r'^(?:consolidated (?:cash flow statements?|statements? of cash flows).*|合[併并][現现]金流量表)$', re.I),
}
LABELS = {
    'IS': {
        'revenue': ('revenue', 'total revenue', 'turnover', '營業收入合計', '營業收入', '营业收入'),
        'operating_income': ('operating profit', 'operating income', 'profit from operations', '营业利润', '營業利益（損失）', '營業利益'),
        'attributable_net_income': ('profit attributable to owners of the company', 'profit attributable to owners of the parent',
                                    '歸屬於母公司業主之本期淨利（損）', '归属于母公司股东的净利润'),
    },
    'BS': {
        'assets': ('total assets', '資產總計', '资产总计'),
        'liabilities': ('total liabilities', '負債總計', '负债合计'),
        'equity': ('total equity', '權益總計', '所有者权益合计', '股东权益合计'),
        'cash': ('cash and cash equivalents', '現金及約當現金', '现金及现金等价物'),
    },
    'CF': {
        'operating_cash_flow': ('net cash from operating activities', 'net cash generated from operating activities',
                                'net cash generated by operating activities', '營業活動之淨現金流入（流出）', '经营活动产生的现金流量净额'),
    },
}
NUMBER = re.compile(r'(?:[+\-]?\d[\d,]*(?:\.\d+)?|\(\d[\d,]*(?:\.\d+)?\))')
LOCAL_DATES = re.compile(r'(?<!\d)(\d{2,4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日')
LOCAL_CURRENCY = {
    'CNY': r'人民[币幣]', 'TWD': r'新[台臺][币幣]', 'HKD': r'港[币幣元]',
}
SCALES = {'units': 1, 'hundreds': 100, 'thousands': 1000, 'millions': 1000000, 'billions': 1000000000,
          '元': 1, '千元': 1000, '仟元': 1000, '万元': 10000, '萬元': 10000,
          '百万元': 1000000, '百萬元': 1000000}
UNIT_DECLARATION = re.compile(r'^\s*(?:[金幣币][額额別种種]?[：:]|[單单]位[：:]|amounts? (?:in|expressed in)\b|'
                              r'expressed in\b|(?:HK|US|NT)\s*\$\s*[’\']?000\b|(?:HKD|USD|TWD|CNY|RMB)\s+)', re.I)


def normalized(text):
    return unicodedata.normalize('NFKC', text).casefold().strip()


def dates_in(text, taiwan):
    found = set(_dates(text))
    for value in re.findall(r'\b\d{1,2} [A-Za-z]+ (?:19|20)\d{2}\b', text):
        try:
            found.add(datetime.strptime(value, '%d %B %Y').date().isoformat())
        except ValueError:
            continue
    for year, month, day in LOCAL_DATES.findall(text):
        year = int(year)
        if taiwan and 10 < year < 200:
            year += 1911
        try:
            found.add(date(year, int(month), int(day)).isoformat())
        except ValueError:
            continue
    return found


def section_unit(header):
    declarations = [line for line in header if UNIT_DECLARATION.search(line)]
    amounts = set()
    for line in declarations:
        currencies = {currency for currency in CURRENCIES if re.search(
            f'(?:{CURRENCIES[currency]})|(?:{LOCAL_CURRENCY.get(currency, "(?!)")})', line, re.I)}
        # Chinese shorthand is only meaningful with a named currency.
        currencies |= {code for code, symbol in [('HKD', 'HK'), ('USD', 'US'), ('TWD', 'NT')]
                       if re.search(rf'{symbol}\s*\$', line, re.I)}
        scales = {value for scale, value in SCALES.items() if scale.isascii() and
                  re.search(rf'\b{scale}\b', line, re.I)}
        local = re.findall(r'[百]?[萬万]元|[仟千]元|(?<![萬万仟千百])元', line)
        scales |= {SCALES[token] for token in local if token in SCALES}
        if re.search(r"\$\s*[’']?000\b", line):
            scales.add(1000)
        if len(currencies) == len(scales) == 1:
            amounts.add((currencies.pop(), scales.pop()))
    return next(iter(amounts)) if len(amounts) == 1 else None


def column_cells(line):
    if isinstance(line, list):
        return [(index, cell.strip()) for index, cell in enumerate(line) if cell.strip()]
    return [(match.end(), match[0]) for match in re.finditer(r'\S(?:.*?\S)?(?=\s{2,}|$)', line.rstrip())]


def line_text(line):
    return '  '.join(line) if isinstance(line, list) else line.strip()


def annual_columns(header, filing, statement):
    """Require a literal current/prior column pair and the approved fiscal end."""
    end = str(filing.period_end)
    taiwan = filing.venue in {'TWSE', 'TPEX'}
    text_header = [line_text(line) for line in header]
    has_exact_end = any(end in dates_in(line, taiwan) for line in text_header)
    calendar = (filing.period_start == date(filing.period_end.year, 1, 1)
                and filing.period_end == date(filing.period_end.year, 12, 31))
    calendar_certificate = any(re.search(r'\d{2,4}\s*年度|\d{4}\s*年\s*1\s*[—–－~-]\s*12\s*月',
                                         line) for line in text_header)
    if not has_exact_end and (statement == 'BS' or not calendar or not calendar_certificate):
        return None
    if statement != 'BS':
        if any(re.search(r'half[- ]year|months? ended|interim|quarter|半年度|季度|期中', line, re.I) for line in text_header):
            return None
        if not calendar_certificate and not any(re.search(r'\byears? ended\b|(?<!半)年度|民國\s*\d{2,3}\s*年\s*1\s*月\s*1\s*日',
                             line, re.I) for line in text_header):
            return None
    expected = filing.period_end.year
    for line in header:
        cells = [(position, value) for position, value in column_cells(line)
                 if not re.fullmatch(r'notes?|附註|附注', value, re.I)]
        if len(cells) != 2:
            continue
        positions = tuple(position for position, _ in cells)
        columns = [value for _, value in cells]
        current, prior = (dates_in(col, taiwan) for col in columns)
        if current == {end} and len(prior) == 1 and int(next(iter(prior))[:4]) == expected - 1:
            return positions, isinstance(line, list)
        years = [re.fullmatch(r'(\d{2,4})(?:\s*年(?:度)?)?', col) for col in columns]
        if all(years):
            pair = [int(match[1]) for match in years]
            if taiwan and max(pair) < 200:
                pair = [year + 1911 for year in pair]
            if pair == [expected, expected - 1]:
                return positions, isinstance(line, list)
    return None


def parse_blocks(blocks, filing):
    rows = []
    aliases = {statement: {normalized(label): (metric, label) for metric, labels in names.items() for label in labels}
               for statement, names in LABELS.items()}
    for location, lines in blocks:
        for index, line in enumerate(lines):
            statement = next((code for code, heading in HEADINGS.items() if heading.fullmatch(line_text(line))), None)
            if not statement:
                continue
            section = []
            for candidate in lines[index + 1:]:
                if any(heading.fullmatch(line_text(candidate)) for heading in HEADINGS.values()):
                    break
                section.append(candidate)
            header = section[:12]
            unit = section_unit([line_text(item) for item in header])
            col_layout = annual_columns(header, filing, statement)
            if unit is None or not col_layout:
                continue
            currency, scale = unit
            positions, structured = col_layout
            # Use exact HTML column indices and right-aligned PDF columns.
            tolerance = 0 if structured else min(8, (positions[1] - positions[0] - 1) // 3)
            for number, line in enumerate(section[:100], index + 2):
                if structured != isinstance(line, list):
                    continue
                cells = column_cells(line)
                if filing.venue in {'TWSE', 'TPEX'} and cells and re.fullmatch(r'\d{4}', cells[0][1]):
                    cells = cells[1:]
                if not cells:
                    continue
                found = aliases[statement].get(normalized(cells[0][1]))
                if found is None:
                    continue
                amounts = [[value for actual, value in cells[1:] if abs(actual - expected) <= tolerance
                            and NUMBER.fullmatch(value)] for expected in positions]
                if any(len(values) != 1 for values in amounts):
                    continue
                metric, definition = found
                rows.append(dict(metric=metric, definition=definition, statement=statement,
                                 period_start=str(filing.period_end if statement == 'BS' else filing.period_start),
                                 period_end=str(filing.period_end),
                                 period_kind='INSTANT' if statement == 'BS' else 'FY',
                                 scope='CONSOLIDATED', currency=currency, unit='CURRENCY', scale=str(scale),
                                 value=decimal_text(amounts[0][0]), parser_version='public-statement-1',
                                 source_locator=f'{location} line {number}: {definition}'))
    counts = Counter(row['metric'] for row in rows)
    return [row for row in rows if counts[row['metric']] == 1]


def parse_statement(raw, kind, filing):
    if raw.startswith(b'%PDF-') and kind in {'application/pdf', 'application/octet-stream', ''}:
        from pypdf import PdfReader
        from pypdf.errors import PdfReadError
        try:
            pages = PdfReader(BytesIO(raw)).pages
            blocks = [(f'PDF page {index}', [line for line in page.extract_text(extraction_mode='layout').splitlines()
                                            if line.strip()])
                      for index, page in enumerate(pages[:MAX_PAGES], 1)]
        except (PdfReadError, ValueError, KeyError):
            raise StatementError('PDF_TEXT_EXTRACTION_FAILED') from None
        cover = ' '.join(' '.join(lines)[:6000] for _, lines in blocks[:3])
    elif kind in {'text/html', 'application/xhtml+xml'} and not raw.startswith(b'%PDF-'):
        from bs4 import BeautifulSoup
        soup = BeautifulSoup(raw, 'html.parser')
        for tag in soup(['script', 'style', 'iframe', 'template']):
            tag.decompose()
        cover = soup.get_text(' ', strip=True)[:8000]
        blocks = []
        for index, table in enumerate(soup.find_all('table', limit=300), 1):
            preceding = table.find_previous_siblings(['p', 'h1', 'h2', 'h3', 'div'], limit=8)
            lines = [tag.get_text(' ', strip=True) for tag in reversed(preceding) if not tag.find('table')]
            if table.find(attrs={'rowspan': True}) or table.find(attrs={'colspan': True}):
                continue
            lines.extend([cell.get_text(' ', strip=True) for cell in row.find_all(['td', 'th'], recursive=False)]
                         for row in table.find_all('tr', limit=300))
            blocks.append((f'HTML table {index}', lines))
    else:
        raise StatementError('UNSUPPORTED_OFFICIAL_ATTACHMENT_CONTENT')
    identity = document_identity(filing.issuer_name, cover)
    if identity != 'OPERATOR_ISSUER_NAME_FOUND_IN_FRONT_MATTER':
        # Common CJK legal names are single tokens and often shorter than eight characters.
        issuer = normalized(filing.issuer_name)
        if not re.fullmatch(r'[\u3400-\u9fff]{5,}', issuer) or issuer not in normalized(cover):
            raise StatementError('OFFICIAL_DOCUMENT_ISSUER_NAME_UNCONFIRMED')
    return parse_blocks(blocks, filing)
